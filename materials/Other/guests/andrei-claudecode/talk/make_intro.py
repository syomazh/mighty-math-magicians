"""Pictures and numbers for intro_slides.tex (the mathematical introduction of the talk).

Run from this folder:

    python3 make_intro.py > make_intro_output.txt

It does two things.

1. It lists all q-ary trees with n internal nodes, for the two small cases shown on the
   slides, and writes them as TikZ pictures to intro_trees.tex. The pictures are
   listed by the program, not drawn by hand, so their number is the tree count.
2. It checks every number that is printed on the slides and prints a log.

The tree counts are found by listing trees or by the recursion "a tree is a leaf or a
root with q subtrees". The closed formula is used in one place only: check 3 compares
it with those counts. Standard library only.
"""

from itertools import product
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---------------------------------------------------------------- trees

LEAF = ()


def compositions(total, parts):
    """All ways to write total as an ordered sum of `parts` non-negative integers."""
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in compositions(total - first, parts - 1):
            yield (first,) + rest


def trees(q, n, _memo={}):
    """All q-ary plane trees with n internal nodes. A leaf is (), a node is a q-tuple."""
    key = (q, n)
    if key not in _memo:
        if n == 0:
            _memo[key] = [LEAF]
        else:
            out = []
            for comp in compositions(n - 1, q):
                for kids in product(*(trees(q, c) for c in comp)):
                    out.append(tuple(kids))
            _memo[key] = out
    return _memo[key]


def leaves(t):
    return 1 if t == LEAF else sum(leaves(c) for c in t)


def internal(t):
    return 0 if t == LEAF else 1 + sum(internal(c) for c in t)


def count_by_recursion(q, nmax):
    """Number of q-ary trees with 0..nmax internal nodes, without listing them."""
    T = [1] + [0] * nmax
    for n in range(1, nmax + 1):
        P = [1] + [0] * (n - 1)  # ordered tuples of trees, by total size
        for _ in range(q):
            P = [sum(P[i] * T[j - i] for i in range(j + 1)) for j in range(n)]
        T[n] = P[n - 1]
    return T


# ---------------------------------------------------------------- pictures


def layout(t):
    """Leaves at x = 0, 1, 2, ...; a node sits midway between its first and last child."""
    nodes, edges = [], []
    counter = [0]

    def place(t, depth):
        if t == LEAF:
            x = float(counter[0])
            counter[0] += 1
            nodes.append((x, depth, False))
            return x
        xs = [place(c, depth + 1) for c in t]
        x = (xs[0] + xs[-1]) / 2
        nodes.append((x, depth, True))
        for cx in xs:
            edges.append((x, depth, cx, depth + 1))
        return x

    place(t, 0)
    return nodes, edges


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s else "0"


def tikz(t):
    nodes, edges = layout(t)
    out = [r"\begin{tikzpicture}[x=\tx,y=\ty,baseline={(0,0)}]"]
    for x0, d0, x1, d1 in edges:
        out.append(rf"\draw[tedge] ({fmt(x0)},{-d0})--({fmt(x1)},{-d1});")
    for x, d, inner in nodes:
        out.append(rf"\node[{'tin' if inner else 'tlf'}] at ({fmt(x)},{-d}) {{}};")
    out.append(r"\end{tikzpicture}")
    return "".join(out)


def macro(name, family, per_row=None):
    """A macro that sets the trees in a row (or in rows of per_row)."""
    pics = [tikz(t) for t in family]
    rows = [pics] if not per_row else [pics[i:i + per_row] for i in range(0, len(pics), per_row)]
    body = "\\\\[\\trowsep]\n".join("\\hspace{\\tsep}".join(r) for r in rows)
    return f"\\newcommand{{\\{name}}}{{%\n{body}}}\n"


FAMILIES = [
    ("TreesBinaryThree", 2, 3, None),   # slide 2, left: the five binary trees
    ("TreesTernaryTwo", 3, 2, None),    # slide 2, right: the three ternary trees
]


def write_pictures():
    head = (
        "% Generated by make_intro.py (written by Claude Fable 5.2 in Claude Code, started by Andrei,\n"
        "% 2026-11-15). Do not edit by hand: run the script again. Not human-reviewed.\n"
    )
    parts = [head]
    for name, q, n, per_row in FAMILIES:
        parts.append(f"% {name}: all {len(trees(q, n))} trees with q = {q}, n = {n}\n")
        parts.append(macro(name, trees(q, n), per_row))
    (HERE / "intro_trees.tex").write_text("".join(parts))


# ---------------------------------------------------------------- checks


def digits(m, p):
    d = []
    while m:
        d.append(m % p)
        m //= p
    return d[::-1]


def vp(x, p):
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


RESULTS = []


def check(name, ok, detail=""):
    RESULTS.append(ok)
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + (f"   {detail}" if detail else ""))


def main():
    print("# Output of make_intro.py, a script written by Claude Fable 5.2 in Claude Code, "
          "started by Andrei, 2026-11-15. Not human-reviewed.")
    write_pictures()

    # 1. The pictures of slide 2: as many trees as the slide says, each with the right shape.
    shown = {(2, 3): 5, (3, 2): 3}
    ok = True
    for (q, n), expected in shown.items():
        fam = trees(q, n)
        ok &= len(fam) == expected and len(set(fam)) == expected
        ok &= all(internal(t) == n and leaves(t) == (q - 1) * n + 1 for t in fam)
    check("1 pictures: 5 binary trees (n = 3) and 3 ternary trees (n = 2), all different, "
          "each with n internal nodes and (q-1)n+1 leaves", ok)

    # 2. Listing and recursion agree, and the rows of values printed on slide 2.
    ok = all(len(trees(q, n)) == count_by_recursion(q, 6)[n] for q in (2, 3, 4) for n in range(7))
    check("2a listing the trees and the recursion give the same counts (q = 2, 3, 4; n <= 6)", ok)
    rows = {2: [1, 2, 5, 14, 42], 3: [1, 3, 12, 55, 273]}
    ok = all(count_by_recursion(q, len(r))[1:] == r for q, r in rows.items())
    check("2b values on slide 2", ok, "; ".join(f"q={q}: {r}" for q, r in rows.items()))

    # 3. The closed formulas of slides 2 and 4 against the counts.
    ok = True
    for q in (2, 3, 4, 5, 8, 9):
        T = count_by_recursion(q, 12)
        for n in range(1, 13):
            m = (q - 1) * n + 1
            ok &= comb(q * n, n) % m == 0 and T[n] == comb(q * n, n) // m
    check("3 number of trees = binom(qn, n)/((q-1)n+1)  (q = 2, 3, 4, 5, 8, 9; n <= 12); "
          "for q = 2 this is binom(2n, n)/(n+1)", ok)

    # 4. The statement of slide 3, on the counts (not on the formula).
    ok = True
    for q, p in ((2, 2), (4, 2), (8, 2), (16, 2), (3, 3), (9, 3), (5, 5), (7, 7)):
        T = count_by_recursion(q, 14)
        for n in range(1, 15):
            s = sum(digits((q - 1) * n + 1, p))
            ok &= (s - 1) % (p - 1) == 0 and vp(T[n], p) == (s - 1) // (p - 1)
    check("4 power of p in the number of trees = (digit sum of the number of leaves - 1)/(p-1)  "
          "(q = 2, 4, 8, 16, 3, 9, 5, 7; n <= 14)", ok)

    # 5. The three examples of slide 3: (q = p, n, trees, leaves, leaves in base p, power of p).
    examples = [(2, 3, 5, 4, "100", 0), (3, 2, 3, 5, "12", 1), (3, 8, 43263, 17, "122", 2)]
    ok = True
    print("   p=q  n  trees  leaves  in base p  power of p")
    for p, n, tr, m, base, power in examples:
        T = count_by_recursion(p, n)
        d = digits((p - 1) * n + 1, p)
        ok &= (T[n] == tr and m == (p - 1) * n + 1 and "".join(map(str, d)) == base
               and vp(tr, p) == power == (sum(d) - 1) // (p - 1))
        print(f"   {p}    {n}  {T[n]:5d}  {(p - 1) * n + 1:6d}  {''.join(map(str, d)):>9}  {vp(T[n], p)}")
    check("5 the three examples of slide 3", ok)
    check("5b 43263 = 3^2 * 4807, and 3 does not divide 4807", 43263 == 9 * 4807 and 4807 % 3 != 0)

    # 6. Slide 4: the known proof. Formula + Legendre's formula give the statement.
    ok = True
    for p, k in ((2, 1), (2, 2), (2, 3), (3, 1), (3, 2), (5, 1), (7, 1)):
        q = p ** k
        fact = 1
        for N in range(1, 40):                                   # Legendre, small N
            fact *= N
            ok &= vp(fact, p) * (p - 1) == N - sum(digits(N, p))
        for n in range(1, 200):
            m = (q - 1) * n + 1
            # v_p((qn)!) - v_p(n!) - v_p(m!) by Legendre, times (p - 1):
            legendre = ((q * n - sum(digits(q * n, p))) - (n - sum(digits(n, p)))
                        - (m - sum(digits(m, p))))
            ok &= legendre == sum(digits(m, p)) - 1
    check("6 slide 4: Legendre's formula (N < 40), and with binom(qn, n)/m = (qn)!/(n! m!) "
          "it gives (s_p(m) - 1)/(p - 1)  (q = 2, 4, 8, 3, 9, 5, 7; n < 200)", ok)
    check("6b binom(qn, n)/m = (qn)!/(n! m!)  (q = 2, 3, 4, 5; n < 30)", all(
        comb(q * n, n) * _fact(n) * _fact((q - 1) * n + 1) == _fact(q * n) * ((q - 1) * n + 1)
        for q in (2, 3, 4, 5) for n in range(1, 30)))

    print(f"\n{len(RESULTS)} checks, {sum(RESULTS)} passed")
    return 0 if all(RESULTS) else 1


def _fact(n):
    f = 1
    for i in range(2, n + 1):
        f *= i
    return f


if __name__ == "__main__":
    raise SystemExit(main())
