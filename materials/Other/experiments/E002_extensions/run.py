def run_detail(filename, function):
    """Keep verbose exact tables in generated companion files."""
    with Path(__file__).with_name(filename).open('w', encoding='utf-8', newline='\n') as stream:
        timestamp = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%SZ')
