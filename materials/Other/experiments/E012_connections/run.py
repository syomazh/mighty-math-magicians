    print("\nB. one 4-ary node, children as patterns; orbit sizes under S_4 and under the 8 binary moves")
    pos = [0, 1, 2, 3]
    s4 = list(itertools.permutations(pos))
    # the 2-group: swap inside left pair, swap inside right pair, swap the pairs
    gens = [(1, 0, 2, 3), (0, 1, 3, 2), (2, 3, 0, 1)]
    grp = {tuple(pos)}
    frontier = [tuple(pos)]
    while frontier:
        g = frontier.pop()
        for h in gens:
            gh = tuple(g[i] for i in h)
            if gh not in grp:
                grp.add(gh)
                frontier.append(gh)
    ok &= len(grp) == 8
    for pat in ["aaaa", "aaab", "aabb", "abab", "aabc", "abac", "abcd"]:
        o_s4 = {tuple(pat[i] for i in g) for g in s4}
        o_g = {tuple(pat[i] for i in g) for g in grp}
        is_pow2 = len(o_g) & (len(o_g) - 1) == 0
        ok &= is_pow2
        print(f"   children {pat}: S_4 orbit {len(o_s4):>2}   binary moves orbit {len(o_g)}"
              f"{'' if is_pow2 else '  NOT A POWER OF 2'}")
    print(f"   group generated by the three swaps has {len(grp)} elements (a Sylow 2-subgroup of S_4)")

