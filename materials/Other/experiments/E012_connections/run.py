"""
E012 -- exact statements used in the motivation and connection pictures
(notes/2026-11-14_motivation_and_connections.md, talk/figures/).

  A. Butyl groups. The 55 plane ternary trees with 4 nodes fall into 5 rotation classes of sizes
     1, 9, 9, 9, 27 (tert-butyl, isobutyl, the two mirror-image sec-butyls, n-butyl), and into 4
     classes if reflections are allowed as well. Class counts for n = 1..7 nodes, with and without
     reflections (to compare with OEIS A000625 and A000598).
  B. Bits and bytes (q = 4). The 4 children of a 4-ary node, read as the leaves of a binary block
     of height 2: orbit sizes of child patterns under all 24 permutations (S_4) and under the 8
     moves generated by swapping at the three binary nodes.
  C. Bounded depth (address blocks, dyadic partitions, rhythms). The number of binary trees with m
     leaves and height <= H is divisible by 2^(s_2(m)-1) for every m and H (rotations preserve the
     height); the valuation is exact as soon as the minimal trees fit (reported).  Same for 4-ary
     trees of height <= 3 read as binary trees with leaves at even depth.
  D. Byte-aligned codes. v_2 of the number of 256-ary trees with n nodes is s_2(255 n + 1) - 1.
  E. Population count. v_2(Catalan(n)) = popcount(n+1) - 1.
  F. The two trees of the carry-budget figure (7 leaves): carries at every node.
  G. The 11 shapes of binary trees with 7 leaves by number of asymmetric nodes (figure "levels").
"""
import itertools
import sys
from math import comb


def sp(m, p):
    s = 0
    while m:
        s += m % p
        m //= p
    return s


def vp(x, p):
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


LEAF = ()


def plane_trees(p, n, _memo={}):
    """All plane p-ary trees with n internal nodes, as nested tuples (leaf = ())."""
    key = (p, n)
    if key in _memo:
        return _memo[key]
    if n == 0:
        res = [LEAF]
    else:
        res = []

        def comps(total, parts):
            if parts == 1:
                yield (total,)
                return
            for a in range(total + 1):
                for rest in comps(total - a, parts - 1):
                    yield (a,) + rest

        for comp in comps(n - 1, p):
            for kids in itertools.product(*[plane_trees(p, c) for c in comp]):
                res.append(tuple(kids))
    _memo[key] = res
    return res


def canon(t):
    """Canonical form under cyclic rotation of the children at every node."""
    if t == LEAF:
        return LEAF
    kids = tuple(canon(c) for c in t)
    return min(kids[i:] + kids[:i] for i in range(len(kids)))


def canon_reflect(t):
    """Canonical form under rotations and reflections (dihedral group) at every node."""
    if t == LEAF:
        return LEAF
    kids = tuple(canon_reflect(c) for c in t)
    rots = [kids[i:] + kids[:i] for i in range(len(kids))]
    rev = kids[::-1]
    rots += [rev[i:] + rev[:i] for i in range(len(kids))]
    return min(rots)


def d_of(t):
    if t == LEAF:
        return 0
    kids = [canon(c) for c in t]
    return sum(d_of(c) for c in t) + (0 if len(set(kids)) == 1 else 1)


def leaves(t):
    return 1 if t == LEAF else sum(leaves(c) for c in t)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    ok = True

    # A ---------------------------------------------------------------------------------------
    H = LEAF
    M = (H, H, H)                      # methyl
    E = (H, H, M)                      # ethyl
    named = {
        "tert-butyl": (M, M, M),
        "isobutyl": (H, H, (H, M, M)),
        "sec-butyl (one hand)": (H, M, E),
        "sec-butyl (other hand)": (H, E, M),
        "n-butyl": (H, H, (H, H, E)),
    }
    trees = plane_trees(3, 4)
    classes = {}
    for t in trees:
        classes.setdefault(canon(t), []).append(t)
    sizes = sorted(len(v) for v in classes.values())
    print(f"A. plane ternary trees with 4 nodes: {len(trees)}; rotation classes: {len(classes)}; sizes {sizes}")
    ok &= len(trees) == 55 and sizes == [1, 9, 9, 9, 27]
    seen = set()
    for name, t in named.items():
        c = canon(t)
        seen.add(c)
        d = d_of(t)
        ok &= c in classes and len(classes[c]) == 3 ** d
        print(f"   {name:<24} d = {d}  class size = {len(classes[c]):>2} = 3^{d}")
    ok &= len(seen) == 5
    mirror = lambda t: LEAF if t == LEAF else tuple(mirror(c) for c in t[::-1])
    ok &= canon(mirror(named["sec-butyl (one hand)"])) == canon(named["sec-butyl (other hand)"])
    ok &= canon(named["sec-butyl (one hand)"]) != canon(named["sec-butyl (other hand)"])
    for name in ("tert-butyl", "isobutyl", "n-butyl"):
        ok &= canon(mirror(named[name])) == canon(named[name])
    print("   the two sec-butyl classes are mirror images of each other; the other three are their own mirror image")
    rot_counts, refl_counts = [], []
    for n in range(1, 8):
        ts = plane_trees(3, n)
        rot_counts.append(len({canon(t) for t in ts}))
        refl_counts.append(len({canon_reflect(t) for t in ts}))
        ok &= len(ts) == comb(3 * n, n) // (2 * n + 1)
    print(f"   classes up to rotation,            n = 1..7: {rot_counts}   (compare OEIS A000625)")
    print(f"   classes up to rotation+reflection, n = 1..7: {refl_counts}   (compare OEIS A000598)")
    ok &= rot_counts == [1, 1, 2, 5, 11, 28, 74]

