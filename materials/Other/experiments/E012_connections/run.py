    print("\nF. carries in the two trees of the carry-budget figure (7 leaves, nu = 4, t = 2)")
    o = LEAF
    K1 = (o, o)
    K2 = (K1, K1)
    minimal = (K2, (K1, o))
    cater = (o, (o, (o, (o, (o, (o, o))))))

    def report(t, name):
        tot, wasted = 0, 0

        def walk(u):
            nonlocal tot, wasted
            if u == LEAF:
                return
            ls = [leaves(c) for c in u]
            c = sum(sp(x, 2) for x in ls) - sp(sum(ls), 2)
            sym = len({canon(x) for x in u}) == 1
            tot += c
            if not sym:
                wasted += c
            for x in u:
                walk(x)

        walk(t)
        return tot, wasted, d_of(t)

    for name, t in (("minimal tree", minimal), ("caterpillar", cater)):
        tot, wasted, d = report(t, name)
