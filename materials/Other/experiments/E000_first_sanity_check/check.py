"""
E000 -- first sanity check for Problem 137
(Tree symmetries and p-adic valuations of Fuss-Catalan numbers).

Author: Claude Fable 5.2 (AI), 2026-11-13.  Status: exploratory, not human-reviewed.

Setting.  p prime, q = p^k.  C_n^{(q)} = binom(qn, n) / ((q-1)n + 1) counts q-ary trees
with n internal nodes; such a tree has m = (q-1)n + 1 leaves.  Known (arithmetic) formula:
        v_p(C_n^{(q)}) = t := (s_p(m) - 1) / (p - 1),     s_p = base-p digit sum.

Idea being tested.  View a q-ary node as a complete p-ary block of depth k, so a q-ary
tree is a p-ary tree all of whose leaves sit at depth = 0 (mod k).  Let G be the group
generated by cyclic rotations (Z_p) of the p children at every p-ary node.

 (A) the G-orbit of T has size p^{d(T)}, d(T) = number of p-ary nodes whose p subtrees
     are NOT all G-equivalent ("asymmetric" nodes);
 (B) min d(T) over q-ary trees with n nodes equals t;
 (C) N_min := number of orbits with d = t satisfies
        N_min = C_n^{(q)} / p^t = (-1)^t / prod_j (m_j!)   (mod p),   m_j = base-p digits of m;
 (D) "skeleton" description of minimal orbits: they correspond to cyclic p-ary trees
     (children of a node known up to rotation) whose leaves are labelled by the base-p
     "atoms" of m (digit m_j gives m_j atoms p^j), an atom p^j sitting at depth = -j (mod k).
     So N_min = T(a) / prod_j m_j!, where T(a) counts such trees with DISTINCT labels and
     a_c = number of atoms with exponent = c (mod k);
 (E) "a carry is a collapsing cherry": cyclically permuting p labels of the same class c
     fixes exactly the trees in which those labels form a cherry, giving
        T(a) = -T(a - p*e_c + e_{c+1})   (mod p)        (indices mod k),
     which is base-p carrying modulo p^k - 1 and yields T(a) = (-1)^t (mod p).

Everything here is brute force / exact rational arithmetic; no factorial valuations are
used except to state the target values we compare against.
"""
import itertools
import math
import sys
from collections import defaultdict
from fractions import Fraction
from functools import lru_cache


def digits(m, p):
    ds = []
    while m:
        ds.append(m % p)
        m //= p
    return ds


def fuss(q, n):
    return math.comb(q * n, n) // ((q - 1) * n + 1)


def vp(x, p):
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


def weak_compositions(total, parts):
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in weak_compositions(total - first, parts - 1):
            yield (first,) + rest


class Orbits:
    """G-orbits of q-ary trees (q = p^k), built orbit-by-orbit with exact tree counts."""

    def __init__(self, p, k):
        self.p, self.k, self.q = p, k, p ** k
        self.intern = {}
        self.d = [0]                 # id 0 = single leaf, d = 0
        self.by_n = {0: {0: 1}}      # n -> {orbit id: number of trees in that orbit}

    def pnode(self, kids):
        p = self.p
        key = min(kids[i:] + kids[:i] for i in range(p))
        i = self.intern.get(key)
        if i is None:
            i = len(self.d)
            self.intern[key] = i
            asym = 0 if len(set(key)) == 1 else 1
            self.d.append(sum(self.d[c] for c in key) + asym)
        return i

    def qnode(self, kids):
        level = list(kids)
        for _ in range(self.k):
            level = [self.pnode(tuple(level[i:i + self.p])) for i in range(0, len(level), self.p)]
        return level[0]

    def build(self, n):
        if n in self.by_n:
            return self.by_n[n]
        for j in range(n):
            self.build(j)
        res = defaultdict(int)
        for comp in weak_compositions(n - 1, self.q):
            lists = [list(self.by_n[c].items()) for c in comp]
            for combo in itertools.product(*lists):
                cnt = 1
                for _, c in combo:
                    cnt *= c
                res[self.qnode(tuple(i for i, _ in combo))] += cnt
        self.by_n[n] = dict(res)
        return self.by_n[n]


def make_labelled_counter(p, k):
    """W(delta, a) = T(delta, a) / prod_c a_c!, where T(delta, a) = number of cyclic p-ary
    trees with distinctly labelled leaves, a_c labels of class c, root at depth delta (mod k),
    every class-c leaf at depth = -c (mod k)."""

    @lru_cache(maxsize=None)
    def W(delta, a):
        s = sum(a)
        if s == 1:
            c = a.index(1)
            return Fraction(1) if (c + delta) % k == 0 else Fraction(0)
        return conv(p, (delta + 1) % k, a) / p

    @lru_cache(maxsize=None)
    def conv(r, delta, a):
        s = sum(a)
        if s < r:
            return Fraction(0)
        if r == 1:
            return W(delta, a)
        tot = Fraction(0)
        for b in itertools.product(*[range(x + 1) for x in a]):
            sb = sum(b)
            if sb == 0 or s - sb < r - 1:
                continue
            wb = W(delta, b)
            if wb == 0:
                continue
            tot += wb * conv(r - 1, delta, tuple(x - y for x, y in zip(a, b)))
        return tot

    def T(delta, a):
        val = W(delta, a) * math.prod(math.factorial(x) for x in a)
        assert val.denominator == 1, ("non-integer labelled count", delta, a, val)
        return val.numerator

    return T


def run(p, k, nmax, box):
    q = p ** k
    print(f"\n=== p={p}, k={k}, q={q} ===")
    orb = Orbits(p, k)
    T = make_labelled_counter(p, k)
    ok = True
    print(f"{'n':>3} {'m':>4} {'s_p(m)':>6} {'t':>3} {'C_n':>10} {'v_p':>4} {'min d':>5} "
          f"{'#orbits':>8} {'N_min':>8} {'N_min%p':>7} {'pred%p':>6} {'skeleton':>9}  checks")
    for n in range(1, nmax + 1):
        cls = orb.build(n)
        m = (q - 1) * n + 1
        dg = digits(m, p)
        s = sum(dg)
        assert (s - 1) % (p - 1) == 0
        t = (s - 1) // (p - 1)
        C = fuss(q, n)
        total = sum(cls.values())
        a_total = total == C                                        # enumeration is complete
        a_orbit = all(cnt == p ** orb.d[i] for i, cnt in cls.items())  # (A)
        dmin = min(orb.d[i] for i in cls)
        b_min = dmin == t                                           # (B)
        nmin = sum(1 for i in cls if orb.d[i] == t)
        fact = math.prod(math.factorial(x) for x in dg)
        pred = ((-1) ** t * pow(fact, -1, p)) % p
        c_res = nmin % p == pred and nmin % p != 0                  # (C)
        a = [0] * k
        for j, mj in enumerate(dg):
            a[j % k] += mj
        skel = Fraction(T(0, tuple(a)), fact)
        d_skel = skel == nmin                                       # (D)
        flags = [a_total, a_orbit, b_min, c_res, d_skel, vp(C, p) == t]
        ok &= all(flags)
        print(f"{n:>3} {m:>4} {s:>6} {t:>3} {C:>10} {vp(C, p):>4} {dmin:>5} {len(cls):>8} "
              f"{nmin:>8} {nmin % p:>7} {pred:>6} {str(skel):>9}  "
              + ("all OK" if all(flags) else f"FAIL {flags}"))

    # (E) carry / cherry recursion on labelled trees, all class vectors with total <= box
    tested = bad = nonzero_wrong = 0
    for a in itertools.product(range(box + 1), repeat=k):
        s = sum(a)
        if s == 0 or s > box:
            continue
        val = T(0, a)
        target_ok = sum(x * p ** c for c, x in enumerate(a)) % max(q - 1, 1) == 1 % max(q - 1, 1)
        if (s - 1) % (p - 1) == 0 and target_ok:
            if val % p != ((-1) ** ((s - 1) // (p - 1))) % p:
                nonzero_wrong += 1
        elif val != 0:
            nonzero_wrong += 1
        for c in range(k):
            if a[c] >= p:
                b = list(a)
                b[c] -= p
                b[(c + 1) % k] += 1
                tested += 1
                if (val + T(0, tuple(b))) % p != 0:
                    bad += 1
    print(f"(E) carry recursion T(a) = -T(a - p e_c + e_(c+1)) mod p: {tested} cases, {bad} failures; "
          f"closed-form residue/vanishing mismatches: {nonzero_wrong}")
    ok &= bad == 0 and nonzero_wrong == 0
    return ok


