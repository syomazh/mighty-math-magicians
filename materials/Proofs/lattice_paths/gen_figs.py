import math

BW, BH, GAP = 0.42, 0.42, 0.20      # box width/height, gap between top segments
LV = 0.66                            # vertical distance between levels of the segment forest

def digits(x, p):
    d = []
    while x: d.append(x % p); x //= p
    return d

def tops(N, p):
    segs, pos = [], 0
    d = digits(N, p)
    for i in reversed(range(len(d))):
        for _ in range(d[i]): segs.append((pos, p**i)); pos += p**i
    return segs

def canon(w, p):
    if len(w) == 1: return w
    s = len(w)//p
    f = [canon(w[i*s:(i+1)*s], p) for i in range(p)]
    return min(tuple(f[r:]+f[:r]) for r in range(p))

class Strip:
    """A path drawn as a row of step boxes, with its forest of p-adic segments above."""
    def __init__(self, word, p, x0=0.0, y0=0.0, forest=True, letters=True):
        self.w, self.p, self.x0, self.y0 = word, p, x0, y0
        self.tops = tops(len(word), p)
        self.forest, self.letters = forest, letters
        self.notes = {}
    def x(self, j):            # left edge of position j (j may equal len)
        t = 0
        for i, (a, L) in enumerate(self.tops):
            if j >= a: t = i
        if j >= len(self.w): t = len(self.tops) - 1
        return self.x0 + j*BW + t*GAP
    def xr(self, j): return self.x(j) + BW     # right edge of position j
    def width(self): return self.xr(len(self.w)-1) - self.x0
    def cx(self, a, L): return (self.x(a) + self.xr(a+L-1))/2
    def ny(self, h): return self.y0 + BH + 0.30 + h*LV
    def draw(self):
        o = []
        for j, ch in enumerate(self.w):
            st = 'ebox' if ch == 'E' else 'sbox'
            lab = f"\\textsf{{{ch}}}" if self.letters else ""
            o.append(f"\\node[{st}] at ({self.x(j)+BW/2:.3f},{self.y0+BH/2:.3f}) {{{lab}}};")
        if self.forest:
            for (a, L) in self.tops: o += self.seg(a, L, None)
        return o
    def atom(self, a, L):
        if L == 1: return []
        st = 'eatom' if self.w[a] == 'E' else 'satom'
        return [f"\\draw[{st}] ({self.x(a)-0.035:.3f},{self.y0-0.055:.3f}) rectangle ({self.xr(a+L-1)+0.035:.3f},{self.y0+BH+0.055:.3f});"]
    def seg(self, a, L, parent):
        o = []
        piece = self.w[a:a+L]
        mono = len(set(piece)) == 1
        h = round(math.log(L, self.p)) if L > 1 else 0
        if mono:
            o += self.atom(a, L)
            if parent is not None:
                o.append(f"\\draw[edge] ({parent[0]:.3f},{parent[1]:.3f}) -- ({self.cx(a,L):.3f},{self.y0+BH+0.07:.3f});")
            return o
        s = L//self.p
        forms = [canon(tuple(piece[i*s:(i+1)*s]), self.p) for i in range(self.p)]
        sym = all(f == forms[0] for f in forms)
        me = (self.cx(a, L), self.ny(h))
        if parent is not None:
            o.append(f"\\draw[edge] ({parent[0]:.3f},{parent[1]:.3f}) -- ({me[0]:.3f},{me[1]:.3f});")
        for i in range(self.p): o += self.seg(a+i*s, s, me)
        o.append(f"\\node[{'symn' if sym else 'asymn'}] at ({me[0]:.3f},{me[1]:.3f}) {{}};")
        self.notes[(a, L)] = me
        return o

def lattice(word, x0, y0, u=0.27, line=None, first=None, marks=()):
    """Lattice path from (0,m) to (n,0): E = one step right, S = one step down."""
    n, m = word.count('E'), word.count('S')
    o = []
    for i in range(n+1): o.append(f"\\draw[grid] ({x0+i*u:.3f},{y0:.3f}) -- ({x0+i*u:.3f},{y0+m*u:.3f});")
    for j in range(m+1): o.append(f"\\draw[grid] ({x0:.3f},{y0+j*u:.3f}) -- ({x0+n*u:.3f},{y0+j*u:.3f});")
    if line is not None:
        o.append(f"\\draw[diag] ({x0:.3f},{y0+line*u:.3f}) -- ({x0+n*u:.3f},{y0:.3f});")
    x, y = 0, m
    pts = [(x, y)]
    for k, ch in enumerate(word):
        nx, ny = (x+1, y) if ch == 'E' else (x, y-1)
        st = 'estep' if ch == 'E' else 'sstep'
        if first is not None and k < first: st = 'fstep'
        o.append(f"\\draw[{st}] ({x0+x*u:.3f},{y0+y*u:.3f}) -- ({x0+nx*u:.3f},{y0+ny*u:.3f});")
        x, y = nx, ny; pts.append((x, y))
    for k in marks:
        px, py = pts[k]
        o.append(f"\\fill[black!80] ({x0+px*u:.3f},{y0+py*u:.3f}) circle (1.5pt);")
    for (px, py) in (pts[0], pts[-1]):
        o.append(f"\\fill[black!80] ({x0+px*u:.3f},{y0+py*u:.3f}) circle (1.5pt);")
    return o, (n*u, m*u)

